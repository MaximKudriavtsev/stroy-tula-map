export const toDraft = (detail: ObjectDetail, revisionId: string): ObjectDraft =>
  ObjectDraftSchema.parse({
    objectId: detail.id,
    revisionId,
    version: 1,
    publicationState: 'PUBLISHED',
    fields: {
      id: detail.id,
      projectId: detail.projectId,
      name: detail.name,
      type: detail.type,
      municipalityId: detail.municipalityId,
      address: detail.address,
      status: detail.status,
      progressPercent: detail.progressPercent,
      anchor: detail.anchor,
      dataOrigin: detail.dataOrigin,
      modelQuality: detail.modelQuality,
      ownership: detail.ownership,
      customer: detail.customer,
      contractor: detail.contractor,
      plannedStart: detail.plannedStart,
      plannedFinish: detail.plannedFinish,
      geometries: detail.geometries,
      source: detail.source,
      media: detail.media,
      model: detail.model,
      observationAsOf: detail.observationAsOf,
    },
  });

